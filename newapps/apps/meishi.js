/* 文を画面用にする（空白は少し広めのすきま、＠は空欄） */
const sentenceHTML = s => R(s).replace(/ /g, '<span class="sp"></span>').replace('＠', '<span class="blank" id="blank"></span>') + '。';

const APP = {
  id:'gg.meishi',
  levelDesc(lv) { return { easy:'3択・よく 使う ことば', normal:'4択・同[おな]じ 場面[ばめん]の ことばが まざる', hard:'4択・あまり 使[つか]わない ことば' }[lv]; },
  make(lv) { return sample(MS[lv], SET_SIZE).map(q => Object.assign({}, q, { opts: shuffle([q.a].concat(sample(q.d, optN(q.d.length + 1, 2, q.d.length + 1) - 1))) })); },
  instr() { return 'あいている ところに 入[はい]る ことばを えらんで ください'; },
  render(q) {
    $('stage').innerHTML = `<p class="sentence">${sentenceHTML(q.s)}</p>`;
    choiceButtons(q.opts, o => R(o), o => o === q.a, o => { const b = $('blank'); b.innerHTML = R(o); b.classList.add('filled'); });
  },
  reveal(q) { const b = $('blank'); b.innerHTML = R(q.a); b.classList.add('filled', 'reveal'); revealChoice(o => o === q.a); },
  answerText(q) { return `こたえは 「${q.a}」 です`; },
  itemLabel(q) { return P(q.s).replace('＠', '［' + P(q.a) + '］').replace(/ /g, ''); },
};
