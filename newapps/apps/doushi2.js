const sentenceHTML2 = s => R(s).replace(/ /g, '<span class="sp"></span>').replace('＠', '<span class="blank" id="blank"></span>') + '。';

const APP = {
  id:'gg.doushi2',
  types:[ { key:'use', name:'使[つか]い分[わ]け' }, { key:'form', name:'かたち' }, { key:'mix', name:'まぜる' } ],
  levelDesc(lv, type) {
    const D = {
      use:  { easy:'3択・着[き]る／はく、乗[の]る／降[お]りる など', normal:'3択・窓[まど]が 開[あ]く／窓[まど]を 開[あ]ける、あげる／くれる など', hard:'4択・落[お]ちる／落[お]とす、貸[か]す／借[か]りる など' },
      form: { easy:'2択・見[み]ます／見[み]ました（きのう・あした）', normal:'3択・〜ています、〜て ください など', hard:'4択・〜て、〜たい、〜ましょう など' },
      mix:  { easy:'使[つか]い分[わ]けと かたちを まぜて', normal:'使[つか]い分[わ]けと かたちを まぜて', hard:'使[つか]い分[わ]けと かたちを まぜて' },
    };
    return (D[type] || D.use)[lv];
  },
  make(lv, type) {
    const pool = type === 'mix' ? DV.use[lv].concat(DV.form[lv]) : DV[type === 'form' ? 'form' : 'use'][lv];
    let qs = sample(pool, SET_SIZE);
    if (type === 'mix') {   // まぜるときは 使い分けと かたちが 半分ずつに なるように
      const half = Math.ceil(SET_SIZE / 2);
      qs = shuffle(sample(DV.use[lv], half).concat(sample(DV.form[lv], SET_SIZE - half))).slice(0, SET_SIZE);
    }
    return qs.map(q => Object.assign({}, q, { opts: shuffle([q.a].concat(sample(q.d, optN(q.d.length + 1, 2, q.d.length + 1) - 1))) }));
  },
  instr(q) {
    return q && q.k === 'form' ? '文[ぶん]に 合[あ]う 動詞[どうし]の かたちを えらんで ください' : 'あいている ところに 入[はい]る 動詞[どうし]を えらんで ください';
  },
  render(q) {
    $('stage').innerHTML = `<p class="sentence">${sentenceHTML2(q.s)}</p>`;
    choiceButtons(q.opts, o => R(o), o => o === q.a, o => { const b = $('blank'); b.innerHTML = R(o); b.classList.add('filled'); });
  },
  reveal(q) { const b = $('blank'); b.innerHTML = R(q.a); b.classList.add('filled', 'reveal'); revealChoice(o => o === q.a); },
  answerText(q) { return `こたえは 「${q.a}」 です`; },
  itemLabel(q) { return P(q.s).replace('＠', '［' + P(q.a) + '］').replace(/ /g, ''); },
};
